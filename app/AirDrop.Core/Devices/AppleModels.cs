using System.Globalization;
using System.Text.RegularExpressions;

namespace AirDrop.Core.Devices;

public enum AppleFamily { Unknown, iPhone, iPad, Mac, Watch, VisionPro, iPodTouch }

/// <summary>Shape hints for device art. Phones/iPads: front design; Macs: enclosure.</summary>
public enum AppleForm
{
    Unknown,
    /// <summary>iPhone/iPod touch/iPad with a round Home button.</summary>
    HomeButton,
    /// <summary>iPhone with the TrueDepth notch (X … 14, 16e).</summary>
    Notch,
    /// <summary>iPhone with the Dynamic Island (14 Pro and later).</summary>
    DynamicIsland,
    /// <summary>iPad with thin bezels all round (Face ID / Touch ID in the top button).</summary>
    NoHomeButton,
    Laptop,
    AllInOne,
    MacMini,
    MacStudio,
    /// <summary>Mac Pro / Xserve.</summary>
    Tower,
    Watch,
    Headset,
}

/// <param name="Identifier">Hardware model identifier ("iPhone16,1", "MacBookPro18,3", "Mac14,2").</param>
/// <param name="Name">Apple's marketing name, regional/connectivity variants merged.</param>
/// <param name="Year">Release year (0 = unknown).</param>
/// <param name="Unverified">Only one community source lists it (recent release) or a detail (form) is unconfirmed.</param>
public sealed record AppleModel(string Identifier, string Name, AppleFamily Family, int Year, AppleForm Form, bool Unverified = false)
{
    /// <summary>True when this entry is a fallback for an identifier missing from the table.</summary>
    public bool IsFallback { get; init; }

    /// <summary>Compact name for one-line subtitles: "MacBook Pro 14″ (M1 Pro)", "iPad Pro 11″ (M4)", "Apple Watch Series 9".</summary>
    public string ShortName => AppleModels.Shorten(this);
}

/// <summary>
/// Apple hardware model identifiers → marketing name, family, year and form factor (data in AppleModels.Data.cs,
/// generated by tools/gen-apple-models.py). Unknown identifiers degrade to "iPhone (iPhone19,3)" with a best-guess form.
/// </summary>
public static partial class AppleModels
{
    // Lazy: Table lives in the other partial file, and static initialisers across partial files run in file order.
    private static readonly Lazy<Dictionary<string, AppleModel>> Index = new(BuildIndex);
    private static Dictionary<string, AppleModel> ById => Index.Value;

    private static Dictionary<string, AppleModel> BuildIndex()
    {
        var d = new Dictionary<string, AppleModel>(StringComparer.OrdinalIgnoreCase);
        foreach (var m in Table) d.TryAdd(m.Identifier, m);
        return d;
    }

    public static IReadOnlyCollection<AppleModel> All => ById.Values;

    /// <summary>Exact table entry or null.</summary>
    public static AppleModel? Find(string? identifier) =>
        identifier is not null && ById.TryGetValue(identifier.Trim(), out var m) ? m : null;

    /// <summary>Table entry, or a fallback built from the identifier's prefix (null for empty / non-Apple strings).</summary>
    public static AppleModel? Resolve(string? identifier)
    {
        if (string.IsNullOrWhiteSpace(identifier)) return null;
        var id = identifier.Trim();
        if (Find(id) is { } m) return m;
        var family = FamilyOf(id);
        if (family == AppleFamily.Unknown) return null;
        return new AppleModel(id, FallbackName(family, id), family, 0, GuessForm(family, id)) { IsFallback = true };
    }

    /// <summary>Friendly name; unknown Apple ids → "iPhone (iPhone19,3)"; non-Apple strings are returned as they are.</summary>
    public static string Describe(string? identifier) =>
        Resolve(identifier)?.Name ?? identifier?.Trim() ?? "";

    /// <summary>Family from the identifier prefix (works for ids not in the table).</summary>
    public static AppleFamily FamilyOf(string? identifier)
    {
        if (string.IsNullOrWhiteSpace(identifier) || !IdPattern().IsMatch(identifier.Trim())) return AppleFamily.Unknown;
        var id = identifier.Trim();
        if (id.StartsWith("iPhone", StringComparison.OrdinalIgnoreCase)) return AppleFamily.iPhone;
        if (id.StartsWith("iPad", StringComparison.OrdinalIgnoreCase)) return AppleFamily.iPad;
        if (id.StartsWith("iPod", StringComparison.OrdinalIgnoreCase)) return AppleFamily.iPodTouch;
        if (id.StartsWith("Watch", StringComparison.OrdinalIgnoreCase)) return AppleFamily.Watch;
        if (id.StartsWith("RealityDevice", StringComparison.OrdinalIgnoreCase)) return AppleFamily.VisionPro;
        if (id.StartsWith("Mac", StringComparison.OrdinalIgnoreCase) || id.StartsWith("iMac", StringComparison.OrdinalIgnoreCase)
            || id.StartsWith("Xserve", StringComparison.OrdinalIgnoreCase))
            return AppleFamily.Mac;
        return AppleFamily.Unknown;
    }

    private static string FallbackName(AppleFamily family, string id) => family switch
    {
        AppleFamily.iPhone => $"iPhone ({id})",
        AppleFamily.iPad => $"iPad ({id})",
        AppleFamily.iPodTouch => $"iPod touch ({id})",
        AppleFamily.Watch => $"Apple Watch ({id})",
        AppleFamily.VisionPro => $"Apple Vision ({id})",
        _ when id.StartsWith("MacBookAir", StringComparison.OrdinalIgnoreCase) => $"MacBook Air ({id})",
        _ when id.StartsWith("MacBookPro", StringComparison.OrdinalIgnoreCase) => $"MacBook Pro ({id})",
        _ when id.StartsWith("MacBook", StringComparison.OrdinalIgnoreCase) => $"MacBook ({id})",
        _ when id.StartsWith("iMac", StringComparison.OrdinalIgnoreCase) => $"iMac ({id})",
        _ when id.StartsWith("Macmini", StringComparison.OrdinalIgnoreCase) => $"Mac mini ({id})",
        _ when id.StartsWith("MacPro", StringComparison.OrdinalIgnoreCase) => $"Mac Pro ({id})",
        _ => $"Mac ({id})",
    };

    /// <summary>Best guess for ids newer than the table: new iPhones have the island, new iPads no Home button.</summary>
    private static AppleForm GuessForm(AppleFamily family, string id)
    {
        int major = Major(id);
        return family switch
        {
            AppleFamily.iPhone => major >= 15 ? AppleForm.DynamicIsland : major >= 11 ? AppleForm.Notch : AppleForm.HomeButton,
            AppleFamily.iPad => major >= 13 ? AppleForm.NoHomeButton : AppleForm.HomeButton,
            AppleFamily.iPodTouch => AppleForm.HomeButton,
            AppleFamily.Watch => AppleForm.Watch,
            AppleFamily.VisionPro => AppleForm.Headset,
            _ when id.StartsWith("MacBook", StringComparison.OrdinalIgnoreCase) => AppleForm.Laptop,
            _ when id.StartsWith("iMac", StringComparison.OrdinalIgnoreCase) => AppleForm.AllInOne,
            _ when id.StartsWith("Macmini", StringComparison.OrdinalIgnoreCase) => AppleForm.MacMini,
            _ when id.StartsWith("MacPro", StringComparison.OrdinalIgnoreCase) || id.StartsWith("Xserve", StringComparison.OrdinalIgnoreCase) => AppleForm.Tower,
            _ => AppleForm.Unknown, // "Mac19,3": the generic MacXX,Y scheme says nothing about the enclosure
        };
    }

    private static int Major(string id)
    {
        var m = IdPattern().Match(id);
        return m.Success ? int.Parse(m.Groups[2].Value, CultureInfo.InvariantCulture) : 0;
    }

    internal static string Shorten(AppleModel m)
    {
        if (m.IsFallback) return m.Name;
        var name = m.Name;
        switch (m.Family)
        {
            case AppleFamily.Watch:
                // "Apple Watch Series 9 (41mm)" → "Apple Watch Series 9"; "Apple Watch SE (1st generation, 40mm)" → "… (1st generation)"
                return Regex.Replace(Regex.Replace(name, @", \d+mm\)", ")"), @"\s*\(\d+mm\)", "");
            case AppleFamily.iPad:
                return InchRegex().Replace(name, "$1″");
            case AppleFamily.Mac:
                int paren = name.IndexOf(" (", StringComparison.Ordinal);
                string product = paren > 0 ? name[..paren] : name;
                string rest = paren > 0 ? name[paren..] : "";
                var inch = Regex.Match(name, @"(\d+(?:\.\d+)?)-inch");
                if (inch.Success && product.EndsWith(inch.Value, StringComparison.Ordinal)) product = product[..^inch.Value.Length].TrimEnd();
                var chip = Regex.Match(rest, @"\bM\d+(?: Pro| Max| Ultra)?\b");
                var year = Regex.Match(rest, @"\b(19|20)\d{2}\b");
                string s = product + (inch.Success ? " " + inch.Groups[1].Value + "″" : "");
                string tag = chip.Success ? chip.Value : year.Success ? year.Value : "";
                return tag.Length > 0 ? $"{s} ({tag})" : s;
            default:
                return name;
        }
    }

    [GeneratedRegex(@"^([A-Za-z]+)(\d+),(\d+)$")]
    private static partial Regex IdPattern();

    [GeneratedRegex(@"(\d+(?:\.\d+)?)-inch")]
    private static partial Regex InchRegex();
}
